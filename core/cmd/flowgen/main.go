// flowgen：从 Go 的 flow schema 生成前端 TypeScript 类型。
// Go 是唯一权威；生成文件禁止手改。
package main

import (
	"flag"
	"fmt"
	"os"
	"reflect"
	"strings"

	"microchat/internal/flow"
)

func main() {
	out := flag.String("out", "../../../frontend/web/src/api/flow.generated.ts", "output TypeScript file")
	flag.Parse()
	var b strings.Builder
	b.WriteString("// Code generated by core/cmd/flowgen; DO NOT EDIT.\n")
	b.WriteString("// Source: core/internal/flow/schema.go\n\n")
	b.WriteString("export type FlowNodeType = ")
	quoted := make([]string, 0, len(flow.NodeTypes))
	for _, kind := range flow.NodeTypes {
		quoted = append(quoted, fmt.Sprintf("%q", kind))
	}
	b.WriteString(strings.Join(quoted, " | "))
	b.WriteString(";\n\n")
	writeStruct(&b, reflect.TypeOf(flow.Position{}), "FlowPosition", nil)
	writeStruct(&b, reflect.TypeOf(flow.Prompt{}), "FlowPrompt", map[string]string{"Role": "string", "Kind": "string"})
	writeStruct(&b, reflect.TypeOf(flow.NodeData{}), "FlowNodeData", map[string]string{"AnswerType": "string"})
	writeStruct(&b, reflect.TypeOf(flow.Node{}), "FlowNode", map[string]string{"Type": "FlowNodeType"})
	writeStruct(&b, reflect.TypeOf(flow.Edge{}), "FlowEdge", nil)
	writeStruct(&b, reflect.TypeOf(flow.Graph{}), "FlowGraph", nil)
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		panic(err)
	}
}

func writeStruct(b *strings.Builder, typ reflect.Type, name string, overrides map[string]string) {
	fmt.Fprintf(b, "export interface %s {\n", name)
	for i := 0; i < typ.NumField(); i++ {
		field := typ.Field(i)
		if field.PkgPath != "" {
			continue
		}
		jsonName := strings.Split(field.Tag.Get("json"), ",")[0]
		if jsonName == "" || jsonName == "-" {
			jsonName = field.Name
		}
		tsType, ok := overrides[field.Name]
		if !ok {
			tsType = tsTypeOf(field.Type)
		}
		optional := field.Type.Kind() == reflect.Pointer || field.Type.Kind() == reflect.Map || strings.Contains(field.Tag.Get("json"), "omitempty")
		if optional && !strings.HasSuffix(tsType, " | undefined") {
			tsType += " | undefined"
		}
		fieldName := jsonName
		if optional {
			fieldName += "?"
		}
		fmt.Fprintf(b, "  %s: %s;\n", fieldName, tsType)
	}
	b.WriteString("}\n\n")
}

func tsTypeOf(t reflect.Type) string {
	if t.Kind() == reflect.Pointer {
		return tsTypeOf(t.Elem())
	}
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Bool:
		return "boolean"
	case reflect.Slice:
		return tsTypeOf(t.Elem()) + "[]"
	case reflect.Map:
		return fmt.Sprintf("Record<%s, %s>", tsTypeOf(t.Key()), tsTypeOf(t.Elem()))
	case reflect.Struct:
		switch t {
		case reflect.TypeOf(flow.Position{}):
			return "FlowPosition"
		case reflect.TypeOf(flow.Prompt{}):
			return "FlowPrompt"
		case reflect.TypeOf(flow.NodeData{}):
			return "FlowNodeData"
		case reflect.TypeOf(flow.Node{}):
			return "FlowNode"
		case reflect.TypeOf(flow.Edge{}):
			return "FlowEdge"
		}
	}
	return "unknown"
}
