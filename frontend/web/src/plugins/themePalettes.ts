export function resolveThemeName(style: ThemeStyle, mode: ColorMode, systemDark: boolean): keyof typeof appThemes {
  const resolved = mode === "auto" ? (systemDark ? "dark" : "light") : mode;
  return style === "miuix" ? `miuix-${resolved}` : resolved;
}
